"""Build docs/TEST-MATRIX.md: every spec T-ID -> the Pest file(s) whose test titles name it.

usage (from the project root): python tools/test-matrix.py
Only IDs written in a test title (it('... T-123 ...')) count; file headers do not.
"""
import glob
import os
import re

NOT_APPLICABLE = {
    'T-116': 'Original browser API client (TypeScript) is replaced by server-side Livewire actions; nothing to test.',
}

TITLE = re.compile(r"\bit\('([^']*)'")
TID = re.compile(r'T-(\d{3})')
ROW = re.compile(r'^\| (T-\d{3}) \| (.*) \|$')

ids = {}
for line in open('docs/SPEC.md', encoding='utf-8').read().splitlines():
    m = ROW.match(line)
    if m:
        ids[m.group(1)] = m.group(2)

coverage = {}
for path in glob.glob('tests/**/*.php', recursive=True):
    rel = path.replace(os.sep, '/')
    for title in TITLE.findall(open(path, encoding='utf-8').read()):
        for n in set(TID.findall(title)):
            coverage.setdefault('T-' + n, set()).add(rel)

rows, covered, na, missing = [], 0, 0, []
for tid, desc in ids.items():
    short = (desc if len(desc) <= 110 else desc[:107] + '…').replace('|', '\\|')
    if tid in coverage:
        covered += 1
        files = ', '.join('`' + f + '`' for f in sorted(coverage[tid]))
        rows.append(f'| {tid} | {short} | {files} | ✅ automated |')
    elif tid in NOT_APPLICABLE:
        na += 1
        rows.append(f'| {tid} | {short} | — | ⏸ {NOT_APPLICABLE[tid]} |')
    else:
        missing.append(tid)
        rows.append(f'| {tid} | {short} | — | ❌ not yet covered |')

out = [
    '# Test matrix',
    '',
    'Generated by `python tools/test-matrix.py` from `docs/SPEC.md` (T-001…T-128) and the Pest suite.',
    'Run the suite with `./vendor/bin/pest` (in-memory SQLite, all outbound HTTP faked).',
    '',
    f'**{covered} automated · {na} not applicable yet · {len(missing)} not covered** (of {len(ids)}).',
    '',
    '| ID | Requirement | Test file(s) | Status |',
    '|---|---|---|---|',
    *rows,
    '',
]
os.makedirs('docs', exist_ok=True)
open('docs/TEST-MATRIX.md', 'w', encoding='utf-8').write('\n'.join(out))
print(f'{covered} automated, {na} n/a, missing: {missing}')
